BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE MODERACION_ACCION CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE MODERACION_ACCION (
    ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TIPO_CONTENIDO VARCHAR2(20)  NOT NULL,
    CONTENIDO_ID   NUMBER        NOT NULL,
    ACCION         VARCHAR2(20)  NOT NULL,
    MOTIVO         VARCHAR2(500),
    MODERADOR_ID   NUMBER,
    FECHA          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_MOD_TIPO   CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONSTRAINT CK_MOD_ACCION CHECK (ACCION IN ('BANEAR', 'DESBANEAR')),
    CONSTRAINT FK_MOD_MODERADOR FOREIGN KEY (MODERADOR_ID) REFERENCES USUARIO (ID) ON DELETE SET NULL
);

CREATE INDEX IX_MOD_CONTENIDO ON MODERACION_ACCION (TIPO_CONTENIDO, CONTENIDO_ID);
CREATE INDEX IX_MOD_MODERADOR ON MODERACION_ACCION (MODERADOR_ID);

-- Historial inicial: registra los baneos de ejemplo que deja 02_foro.sql
INSERT INTO MODERACION_ACCION (TIPO_CONTENIDO, CONTENIDO_ID, ACCION, MOTIVO, MODERADOR_ID)
SELECT 'TEMA', T.ID, 'BANEAR', T.MOTIVO_BANEO, (SELECT ID FROM USUARIO WHERE EMAIL = 'moderador@foro.cl')
FROM TEMA T WHERE T.ESTADO = 'BANEADO';

INSERT INTO MODERACION_ACCION (TIPO_CONTENIDO, CONTENIDO_ID, ACCION, MOTIVO, MODERADOR_ID)
SELECT 'COMENTARIO', C.ID, 'BANEAR', C.MOTIVO_BANEO, (SELECT ID FROM USUARIO WHERE EMAIL = 'moderador@foro.cl')
FROM COMENTARIO C WHERE C.ESTADO = 'BANEADO';

COMMIT;

SELECT * FROM MODERACION_ACCION ORDER BY FECHA DESC;
